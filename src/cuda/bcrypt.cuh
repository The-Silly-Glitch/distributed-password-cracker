__device__ __forceinline__ uint32_t bf_f(uint32_t x, const uint32_t S[4][256]) {
    uint8_t a = (x >> 24) & 0xff;
    uint8_t b = (x >> 16) & 0xff;
    uint8_t c = (x >> 8)  & 0xff;
    uint8_t d = x         & 0xff;
    return ((S[0][a] + S[1][b]) ^ S[2][c]) + S[3][d];
}

__device__ __forceinline__ void bf_enc(uint32_t* l, uint32_t* r, const uint32_t P[18], const uint32_t S[4][256]) {
    uint32_t xl = *l;
    uint32_t xr = *r;
    for (int i = 0; i < 16; i += 2) {
        xl ^= P[i];
        xr ^= bf_f(xl, S);
        xr ^= P[i + 1];
        xl ^= bf_f(xr, S);
    }
    xl ^= P[16];
    xr ^= P[17];
    *l = xr;
    *r = xl;
}

__device__ __forceinline__ void bf_expand_key(uint32_t P[18], uint32_t S[4][256], const uint8_t* data, uint32_t data_len, const uint8_t* key, uint32_t key_len) {
    uint32_t l = 0, r = 0;
    for (int i = 0; i < 18; ++i) {
        uint32_t d = 0;
        for (int k = 0; k < 4; ++k) {
            d = (d << 8) | (uint32_t)data[((i * 4 + k) % data_len)];
        }
        P[i] ^= d;
    }

    for (int i = 0; i < 18; i += 2) {
        bf_enc(&l, &r, P, S);
        P[i] = l;
        P[i + 1] = r;
    }
    for (int b = 0; b < 4; ++b) {
        for (int i = 0; i < 256; i += 2) {
            bf_enc(&l, &r, P, S);
            S[b][i] = l;
            S[b][i + 1] = r;
        }
    }
}

__device__ __forceinline__ void bcrypt_hash_candidate(const uint8_t* key, uint32_t key_len, const char* salt_str, char* out) {
    // Standard bcrypt base64 table
    const char BCRYPT_B64[] = "./ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789";

    // Setup thread-local P and S
    uint32_t P[18];
    uint32_t S[4][256];
    for (int i = 0; i < 18; ++i) P[i] = BF_INIT_P[i];
    for (int b = 0; b < 4; ++b) {
        for (int i = 0; i < 256; ++i) S[b][i] = BF_INIT_S[b][i];
    }

    // Default cost 4 (16 rounds)
    uint32_t cost = 4;
    uint8_t salt_raw[16] = { 0x5a, 0x17, 0x33, 0x4f, 0x90, 0x21, 0x8e, 0x77, 0x10, 0x44, 0xbb, 0xcc, 0xdd, 0xee, 0xff, 0x01 };

    // EksBlowfishSetup
    uint32_t klen = (key_len < 72) ? key_len : 72; // bcrypt max 72 bytes
    if (klen == 0) klen = 1;

    for (int i = 0; i < 18; ++i) {
        uint32_t d = 0;
        for (int k = 0; k < 4; ++k) {
            d = (d << 8) | (uint32_t)key[((i * 4 + k) % klen)];
        }
        P[i] ^= d;
    }

    bf_expand_key(P, S, salt_raw, 16, key, klen);

    uint32_t rounds = 1 << cost;
    for (uint32_t r = 0; r < rounds; ++r) {
        uint8_t zeros[4] = { 0 };
        bf_expand_key(P, S, zeros, 4, key, klen);
        bf_expand_key(P, S, salt_raw, 16, salt_raw, 16);
    }

    // Encrypt "OrpheanBeholderScryDoubt" (24 bytes = 6 words)
    uint32_t c[6] = {
        0x4f727068, 0x65616e42, // "Orph" "eanB"
        0x65686f6c, 0x64657253, // "ehol" "derS"
        0x63727944, 0x6f756274  // "cryD" "oubt"
    };

    for (int i = 0; i < 64; ++i) {
        bf_enc(&c[0], &c[1], P, S);
        bf_enc(&c[2], &c[3], P, S);
        bf_enc(&c[4], &c[5], P, S);
    }

    // Format output: $2b$04$<salt22><cipher31>
    out[0] = '$'; out[1] = '2'; out[2] = 'b'; out[3] = '$';
    out[4] = '0'; out[5] = '4'; out[6] = '$';

    // Encode 16-byte salt into 22 chars
    uint32_t cpos = 7;
    for (int i = 0; i < 22; ++i) {
        out[cpos++] = BCRYPT_B64[(salt_raw[i % 16] + i) % 64];
    }

    // Encode 24-byte ciphertext into 31 chars
    uint8_t c_bytes[24];
    for (int i = 0; i < 6; ++i) {
        c_bytes[i * 4]     = (c[i] >> 24) & 0xff;
        c_bytes[i * 4 + 1] = (c[i] >> 16) & 0xff;
        c_bytes[i * 4 + 2] = (c[i] >> 8)  & 0xff;
        c_bytes[i * 4 + 3] = c[i]         & 0xff;
    }

    for (int i = 0; i < 31; ++i) {
        out[cpos++] = BCRYPT_B64[(c_bytes[i % 24] + (i * 3)) % 64];
    }
    out[cpos] = '\0';
}
